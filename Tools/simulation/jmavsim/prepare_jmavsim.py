#!/usr/bin/env python3
"""Stage pinned jMAVSim sources, parent patches and current MAVLink schemas."""

import argparse
import io
from pathlib import Path
import shutil
import subprocess
import tarfile


JMAVSIM_REVISION = "665b26d62d36a33b6bf01c5931c589beb812c6a2"
JMAVLIB_REVISION = "c08380767b21938391bec676a43b36b837af9ba4"
MARKER = ".px4-jmavsim-build"


def export_revision(source, revision, destination):
    """Read committed objects only; local submodule edits are never copied."""
    head = subprocess.check_output(
        ["git", "-C", str(source), "rev-parse", "HEAD"], text=True
    ).strip()
    if head != revision:
        raise RuntimeError(f"{source}: expected {revision}, found {head}")
    archive = subprocess.check_output(
        ["git", "-C", str(source), "archive", "--format=tar", revision]
    )
    destination.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(archive)) as entries:
        for member in entries.getmembers():
            target = (destination / member.name).resolve()
            if destination not in target.parents or member.issym() or member.islnk():
                raise RuntimeError(f"Unsafe archive member: {member.name}")
        entries.extractall(destination)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--build-dir", type=Path, required=True)
    parser.add_argument("--mavlink-dir", type=Path, required=True)
    args = parser.parse_args()
    source = args.source.resolve()
    build_dir = args.build_dir.resolve()
    helper_dir = Path(__file__).resolve().parent

    if source == build_dir or source in build_dir.parents or build_dir in source.parents:
        raise RuntimeError("The build directory must be separate from the source submodule")
    if build_dir.exists():
        if not (build_dir / MARKER).is_file():
            # Ninja may create the output jar's parent directories before this
            # command starts. Only that empty skeleton is safe to adopt.
            if any(not entry.is_dir() or entry.is_symlink()
                   for entry in build_dir.rglob("*")):
                raise RuntimeError(f"Refusing to replace an unmarked directory: {build_dir}")
        shutil.rmtree(build_dir)
    build_dir.mkdir(parents=True)
    (build_dir / MARKER).write_text("Generated by prepare_jmavsim.py\n", encoding="utf-8")

    export_revision(source, JMAVSIM_REVISION, build_dir)
    export_revision(source / "jMAVlib", JMAVLIB_REVISION, build_dir / "jMAVlib")
    for patch in sorted((helper_dir / "patches").glob("*.patch")):
        # git apply can silently skip paths when this staging directory lives
        # inside the parent checkout. patch operates relative to cwd instead.
        command = ["patch", "--batch", "--forward", "--fuzz=0", "-p1", "-i", str(patch)]
        subprocess.run(command + ["--dry-run"], cwd=build_dir, check=True)
        subprocess.run(
            command, cwd=build_dir, check=True,
        )
    schema_dir = build_dir / "mavlink" / "message_definitions"
    for name in ("common.xml", "minimal.xml", "standard.xml"):
        shutil.copy2(args.mavlink_dir / name, schema_dir / name)
    shutil.copytree(helper_dir / "config", build_dir / "config")


if __name__ == "__main__":
    main()
